// ===== سجل الطالب حسب اللائحة: التدرج المعتمد في السجل =====
// تُقرأ قيود الطالب بترتيب تسجيلها، ولكل قيد «المستوى الذي عومل به»: مستوى المخالفة نفسها، أو أعلى منه إذا كان تكراراً
// (المادة الثانية: عند التكرار تُطبَّق العقوبة التالية الأشد). المخالفات المسجلة في نفس اليوم تُحسب تكراراً أيضاً.
// التدرج (كل خطوة تُوثَّق بقيد):
//   بسيطة: الأولى تعهد (نصح وإرشاد)، الثانية تعهد (تنبيه)، الثالثة تُعامل كمتوسطة. التقارير لا تُحسب خطوة.
//   متوسطة: تعهد (الإجراء الأول)، ثم استدعاء ولي الأمر وإنذار (الإجراء الثاني)، ثم تُعامل كشديدة.
//   شديدة: لجنة الانضباط، والتكرار بعدها يُعامل كجسيمة (مجلس النظام).
//   البسيطة لا تتجاوز الشديدة مهما تكررت.
const NEXT_LV = {s:'m', m:'h', h:'g'};
const LAIHA_LADDER = [
  'بسيطة: المرة الأولى تعهد (نصح وإرشاد)، والثانية تعهد (تنبيه)، والثالثة تُعامل كمتوسطة.',
  'متوسطة: تعهد (الإجراء الأول)، ثم استدعاء ولي الأمر وإنذار (الإجراء الثاني)، ثم تُعامل كشديدة.',
  'شديدة: استدعاء ولي الأمر وإحالة للجنة الانضباط (حرمان حتى 3 أيام)، والتكرار بعدها يُعامل كجسيمة.',
  'جسيمة: مجلس النظام المدرسي (حرمان حتى 5 أيام، أو نقل لمدرسة أخرى، أو فصل في الثانوية).',
  'البسيطة لا تتجاوز الشديدة مهما تكررت. والبسيطة التي تُعامل كمتوسطة تُحسب خطوة في تدرج المتوسطة.',
  'المخالفات المسجلة في نفس اليوم تُحسب تكراراً. والتقارير لا تُحسب خطوة في تدرج البسيطة، فوثّق خطواتها بتعهدات.'
];
const newState = () => ({raw:{}, eff:{}, same:{}, sdoc:0, pledges:0, summons:0, medSummons:0});
function laihaEscalates(L, st){
  const n = st.eff[L] || 0;
  if (!n || !NEXT_LV[L]) return false;
  if (L === 'm') return n >= 2 || st.medSummons >= 1;
  return true;
}
// المستوى الذي تُعامل به مخالفة جديدة (x) على طالب حالته st
function laihaStep(x, st){
  if (x.lv === 's') {
    if (st.sdoc < 2) return 's';
    let L = 'm';
    while (L !== 'h' && laihaEscalates(L, st)) L = NEXT_LV[L];
    return L;
  }
  if (x.lv !== 'm' && x.lv !== 'h') return x.lv;
  let L = x.lv;
  while (laihaEscalates(L, st)) L = NEXT_LV[L];
  return L;
}
// يضيف قيداً إلى حالة الطالب (الفصل المرفوض لا يُحسب، والاستدعاء يُحسب إذا حلّ موعده أو سُجّلت نتيجته)
function laihaApply(a, x, eff, st){
  if (a.type === 'suspend' && a.status === 'rejected') return;
  if (a.type === 'pledge') st.pledges++;
  const summoned = a.type === 'summon' && (a.status !== 'scheduled' || (a.summonDate || '') <= today());
  if (summoned) { st.summons++; if (eff === 'm') st.medSummons++; }
  if (!x) return;
  if (x.lv === 's' && a.type !== 'report') st.sdoc++;
  st.raw[x.lv] = (st.raw[x.lv] || 0) + 1; st.eff[eff] = (st.eff[eff] || 0) + 1; st.same[x.id] = (st.same[x.id] || 0) + 1;
}
// لكل الطلاب: حالة كل طالب، ومستوى كل قيد بعد احتساب التكرار. تُحسب مرة لكل تغيّر في البيانات
let LMEMO = {ver:-1};
function laihaAll(){
  const m = M();
  if (LMEMO.ver === m.ver) return LMEMO;
  const st = {}, eff = {};
  for (const sid in m.byStu) {
    const s = newState();
    m.byStu[sid].slice().sort((a, b) => (a.createdAt || 0) - (b.createdAt || 0)).forEach(a => {
      const x = laihaOf(a.violation), e = x ? laihaStep(x, s) : '';
      if (x) eff[a.id] = {base:x.lv, eff:e};
      laihaApply(a, x, e, s);
    });
    st[sid] = s;
  }
  LMEMO = {ver:m.ver, st, eff};
  return LMEMO;
}
const laihaState = sid => (sid && laihaAll().st[sid]) || newState();
// شارة القيد: مستوى معاملته، مع «تكرار» إذا ارتفع عن مستوى المخالفة نفسها
function lvChipAct(a){
  const r = laihaAll().eff[a.id];
  if (!r) return '';
  if (r.eff === r.base) return lvChip(r.eff);
  return `<span class="lvchip lv-${r.eff}" title="${esc('المخالفة ' + LV[r.base].l + '، وعوملت كـ' + LV[r.eff].l + ' لأنها تكرار')}">${esc(LV[r.eff].l)} · تكرار</span>`;
}
// ملخص ملف الطالب: عدد القيود بكل مستوى بعد احتساب التكرار
function laihaSummary(sid){
  const s = laihaState(sid), keys = LV_KEYS.filter(k => s.eff[k]);
  if (!keys.length) return '';
  return `<div class="laiha-sum"><span class="meta">حسب اللائحة:</span>${keys.map(k => `<span class="lvchip lv-${k}">${esc(LV[k].l)} ${s.eff[k]}</span>`).join('')}</div>`;
}
const plural = (n, one, two, many) => n === 1 ? one : n === 2 ? two : n + ' ' + many;
// يرجع {x, lv, eff, suggest, label, why, notes:[{tone, html}]} لنص المخالفة وسجل الطالب
function laihaGuide(text, studentId){
  const x = laihaOf(text);
  if (!x) return null;
  const st = laihaState(studentId), eff = laihaStep(x, st), prevSame = st.same[x.id] || 0;
  const notes = [];
  let suggest, label, why;
  if (eff === 's') {
    suggest = 'pledge';
    label = st.sdoc ? 'تعهد خطي (تنبيه)' : 'تعهد خطي (نصح وإرشاد)';
    why = st.sdoc ? 'المرة الثانية في البسيطة: تنبيه يُوثَّق بتعهد. التكرار القادم يُعامل كمتوسطة.'
                  : 'المرة الأولى في البسيطة: نصح وإرشاد يُوثَّق بتعهد. المرة الثانية تعهد، والثالثة تُعامل كمتوسطة.';
  } else if (eff === 'm') {
    const second = (st.eff.m || 0) >= 1;
    suggest = second ? 'summon' : 'pledge';
    label = second ? 'استدعاء ولي الأمر وإنذار' : 'تعهد خطي (الإجراء الأول للمتوسطة)';
    why = second ? 'الإجراء الثاني للمتوسطة: يستدعي المدير المساعد ولي الأمر ويوقّع مع الطالب تعهداً بصيغة إنذار. التكرار القادم يُعامل كشديدة ويُحال للجنة الانضباط.'
                 : 'الإجراء الأول للمتوسطة: تدوين المخالفة من مشرف الجناح وتعهد خطي من الطالب. التكرار القادم: استدعاء ولي الأمر وإنذار.';
  } else if (eff === 'h') {
    suggest = 'summon'; label = 'استدعاء ولي الأمر وإحالة للجنة الانضباط';
    why = 'تُحال للجنة الانضباط السلوكي مع إشعار ولي الأمر، والحرمان حتى 3 أيام بقرارها. ' + (x.lv === 's' ? 'والبسيطة لا تتجاوز الشديدة مهما تكررت.' : 'التكرار القادم يُعامل كجسيمة.');
  } else if (eff === 'g') { suggest = 'suspend'; label = 'فصل بقرار مجلس النظام'; why = 'يعرضها مجلس النظام المدرسي: حرمان حتى 5 أيام، أو نقل لمدرسة أخرى، أو فصل في الثانوية.'; }
  else if (eff === 't') { suggest = 'report'; label = 'تقرير يُعرض على مجلس النظام'; why = 'توثيق الواقعة بتقرير وعرضها على مجلس النظام المدرسي.'; }
  else { suggest = 'report'; label = TYPES.report.long; why = 'إبلاغ الإدارة بتقرير بعد التنبيه داخل الحصة.'; }
  if (eff !== x.lv) {
    const bits = [];
    if (x.lv === 's') bits.push(`على الطالب ${plural(st.sdoc, 'مخالفة بسيطة موثقة سابقة', 'مخالفتان بسيطتان موثقتان سابقتان', 'مخالفات بسيطة موثقة سابقة')}، فهذه تُعامل كمتوسطة (تكرار المشكلة البسيطة)`);
    if ((eff === 'h' || eff === 'g') && x.lv !== 'h') bits.push((st.medSummons ? 'وسبق استدعاء ولي أمره وإنذاره على مخالفة متوسطة' : `وعليه ${plural(st.eff.m, 'مخالفة متوسطة سابقة', 'مخالفتان متوسطتان سابقتان', 'مخالفات متوسطة سابقة')}`) + '، فتُعامل كشديدة (تكرار المتوسطة)');
    if (eff === 'g') bits.push(`وعلى الطالب ${plural(st.eff.h, 'مخالفة سابقة مصنفة شديدة', 'مخالفتان سابقتان مصنفتان شديدة', 'مخالفات سابقة مصنفة شديدة')}، فتُعامل كجسيمة (تكرار الشديدة)`);
    bits[0] = bits[0].replace(/^و/, '');
    notes.push({tone:'warn', html:`<b>تكرار:</b> ${esc(bits.join('، '))}. حسب المادة الثانية تُطبَّق العقوبة التالية الأشد، والجهة ${esc(LV[eff].who)}.`});
  }
  const hist = [st.pledges ? plural(st.pledges, 'تعهد واحد', 'تعهدان', 'تعهدات') : '', st.summons ? plural(st.summons, 'استدعاء واحد لولي الأمر', 'استدعاءان لولي الأمر', 'استدعاءات لولي الأمر') : ''].filter(Boolean);
  // تصنيف المخالفات السابقة بعد احتساب التكرار
  const refs = LV_KEYS.filter(k => st.eff[k]).map(k => `${LV[k].l} ${st.eff[k]}`);
  if (hist.length || refs.length) {
    const serious = st.eff.h || st.eff.g || st.eff.t;
    notes.push({tone: serious ? 'warn' : 'info',
      html:`<b>سجل الطالب:</b> ${hist.length ? 'عليه ' + hist.join(' و') + '.' : ''}${refs.length ? ' مخالفاته السابقة بعد احتساب التكرار: ' + refs.join('، ') + '.' : ''}`});
  }
  if (prevSame) notes.push({tone:'info', html:prevSame === 1 ? 'سُجّلت نفس المخالفة على الطالب مرة سابقة.' : `عدد مرات تسجيل نفس المخالفة على الطالب سابقاً: ${prevSame}.`});
  if (x.note) notes.push({tone:'info', html:esc(x.note)});
  if (x.sp) notes.push({tone:'bad', html:`<b>${esc(LAIHA_SPECIAL[x.sp].h)}:</b> ${LAIHA_SPECIAL[x.sp].steps.map(esc).join(' ')} ${esc(LAIHA_SPECIAL_RULE)}`});
  return {x, lv:x.lv, eff, suggest, label, why, notes};
}
// تنبيه مدة الفصل حسب المستوى بعد احتساب التكرار (يرجع نص التنبيه أو '')
function laihaDaysWarn(text, studentId, days){
  const g = laihaGuide(text, studentId); if (!g) return '';
  const lv = g.eff;
  if (lv === 's') return 'الحرمان من الدراسة ليس من إجراءات المخالفات البسيطة في اللائحة.';
  if (lv === 'm') return 'الحرمان من الدراسة ليس من إجراءات المخالفات المتوسطة في اللائحة.';
  if (LV[lv].days && days > LV[lv].days) return `الحد الأقصى للحرمان من الدراسة في ${lv === 'h' ? 'المخالفة الشديدة' : 'المخالفة الجسيمة'}: ${daysTxt(LV[lv].days)} (المادة الخامسة).`;
  return '';
}
function laihaCard(text, studentId){
  const g = laihaGuide(text, studentId);
  if (!g) {
    if (!text || text === '__other') return '';
    return `<div class="laiha-card lv-o"><div class="lc-h"><span class="lvchip lv-o">غير مصنفة</span><span class="lc-ref">لا يصنّفها الفصل الثاني من اللائحة</span></div>
      <p class="lc-p">الغياب والامتحانات لها لوائحها. وأي مخالفة لم يرد بشأنها نص تُرفع إلى مدير الشؤون التعليمية بالمنطقة (المادة الثانية).</p></div>`;
  }
  const L = LV[g.eff], up = g.eff !== g.lv;
  return `<div class="laiha-card lv-${g.eff}">
    <div class="lc-h">${lvChip(g.lv, true)}${up ? `<span class="lc-arrow" aria-hidden="true">←</span>${lvChip(g.eff)}<span class="lc-ref">تُعامل كـ${esc(L.l)} لأنها تكرار</span>` : ''}</div>
    <div class="lc-ref">${esc(laihaRef(g.x))}</div>
    <div class="lc-row"><span class="lc-k">الجهة</span><span>${esc(L.who)}</span></div>
    <div class="lc-row"><span class="lc-k">الحد الأقصى</span><span>${esc(L.max)}</span></div>
    <details class="lc-steps"><summary>الإجراء حسب اللائحة</summary><ol>${L.steps.map(s => `<li>${esc(s)}</li>`).join('')}</ol></details>
    ${g.notes.map(n => `<div class="banner ${n.tone === 'info' ? '' : n.tone}">${icon(n.tone === 'info' ? 'info' : 'alert')}<div>${n.html}</div></div>`).join('')}
    <div class="lc-sug"><span class="lc-k">المقترح</span><button type="button" class="tchip ty-${g.suggest}" data-act="r-type" data-t="${g.suggest}" aria-pressed="${R && R.type === g.suggest}">${esc(g.label)}</button><span class="lc-why">${esc(g.why)}</span></div>
  </div>`;
}

/* ===== شاشة «اللائحة»: بحث سريع عن تصنيف أي مخالفة ===== */
const LQ = {q:'', lv:'all'};
function laihaMatches(){
  const q = norm(LQ.q);
  return LAIHA.filter(x => (LQ.lv === 'all' || x.lv === LQ.lv) && (!q || norm(x.t + ' ' + (x.k || '')).includes(q) || q.split(' ').every(w => norm(x.t + ' ' + (x.k || '')).includes(w))));
}
function renderLaihaList(){
  const box = $('#lh-list'); if (!box) return;
  $$('#lh-lv [data-act="lh-lv"]').forEach(b => b.setAttribute('aria-pressed', String(b.dataset.lv === LQ.lv)));
  const hits = laihaMatches();
  if (!hits.length) {
    box.innerHTML = `<div class="empty"><h3>لا توجد مخالفة بهذا الاسم</h3><p>جرّب كلمة أخرى. وإذا لم يرد بشأنها نص في اللائحة تُرفع إلى مدير الشؤون التعليمية بالمنطقة (المادة الثانية).</p></div>`;
    return;
  }
  box.innerHTML = LV_KEYS.filter(lv => hits.some(x => x.lv === lv)).map(lv => {
    const L = LV[lv], items = hits.filter(x => x.lv === lv);
    return `<section class="laiha-sec lv-${lv}">
      <div class="ls-h">${lvChip(lv, true)}<span class="lc-ref">${esc(L.ref)}</span></div>
      <div class="lc-row"><span class="lc-k">الجهة</span><span>${esc(L.who)}</span></div>
      <div class="lc-row"><span class="lc-k">الحد الأقصى</span><span>${esc(L.max)}</span></div>
      <details class="lc-steps"${LQ.q ? ' open' : ''}><summary>الإجراء حسب اللائحة</summary><ol>${L.steps.map(s => `<li>${esc(s)}</li>`).join('')}</ol></details>
      <ul class="ls-items">${items.map(x => `<li><span class="ls-n num">${x.n || '•'}</span><span class="ls-t">${esc(x.t)}${x.note ? `<span class="meta">${esc(x.note)}</span>` : ''}${x.sp ? `<span class="meta bad">${esc(LAIHA_SPECIAL[x.sp].h)}</span>` : ''}</span></li>`).join('')}</ul>
    </section>`;
  }).join('');
}
